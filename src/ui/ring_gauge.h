#pragma once
/*
 * ring_gauge.h — двойная кольцевая шкала «полосками» вдоль края экрана.
 * Короткие капсулы-сегменты идут по дуге окружности (экран круглый,
 * шкала отступлена от кромки). Верхняя полуокружность — температура
 * (синий = холодно, бирюза, жёлтый = тепло, красный = жарко),
 * нижняя — влажность или давление.
 */
#include <lvgl.h>

enum RingBottom {
    RING_HUMIDITY,   /* 0..100 %: сухо (янтарный) -> влажно (синий) */
    RING_PRESSURE,   /* монотонная шкала, акцентный цвет */
    RING_TEMP,       /* температура: зелёный -> жёлтый -> оранжевый -> красный (обе половины) */
    RING_SERVER      /* сервер: верх=CPU% (синий->бирюза->жёлтый->красный), низ=CPU temp (зелёный->жёлтый->оранжевый->красный) */
};

lv_obj_t *ring_gauge_create(lv_obj_t *parent, int size);

/* Установить значения: верхняя половина — температура,
 * нижняя — bot в диапазоне [botMin..botMax]. */
void ring_gauge_set(lv_obj_t *gauge,
                    float temp, float tempMin, float tempMax,
                    float bot,  float botMin, float botMax,
                    RingBottom mode);
