#pragma once
/*
 * ens160_aht21.h — датчик воздуха ENS160 + AHT21 (I2C).
 *
 * AHT21  — температура и влажность (адрес 0x38).
 * ENS160 — качество воздуха: eCO2 (ppm), TVOC (ppb), AQI UBA,
 *          сопротивления газовых сенсоров, статус прогрева.
 *          Адрес определяется автоматически (0x52/0x53/0x59 — зависит
 *          от модуля: ScioSense даташит даёт 0x52, некоторые модули 0x59).
 *
 * API устроен как у прежнего bmp280: begin() один раз, read() периодически.
 */
#include "../app_state.h"

/* Инициализация шины I2C и обоих датчиков. true — хотя бы один найден. */
bool sensor_begin();

/* Снять показания. Заполняет out (valid/aht21Ok/ens160Ok выставляются).
 * true — если успешно прочитано хотя бы что-то. */
bool sensor_read(HomeData &out);